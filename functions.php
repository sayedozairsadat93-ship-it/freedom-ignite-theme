# Freedom Ignite Theme

A premium, conversion-focused WordPress theme for events, organizations, and community-driven businesses.

## Features

- Responsive design optimized for desktop, tablet, and mobile
- Sticky header with editable navigation
- High-impact hero layout
- Mission and attraction cards
- Partner logo grid
- CTA sections and registration form
- Gutenberg-friendly structure and theme.json design tokens
- Accessibility-minded markup and focus states
- Built for performance and clean WordPress setup

## Install

1. Open your WordPress admin.
2. Navigate to Appearance → Themes → Add New → Upload Theme.
3. Select the generated theme zip file.
4. Activate the theme.

## Edit homepage content

- Go to WordPress admin → Pages → Home.
- Edit the content directly in the block editor.
- Replace hero images and text using the Media Library.
- Use blocks to add or remove sections.

## Update navigation

- Go to Appearance → Menus.
- Create or update the Primary Menu.
- Select the location as Primary Menu.

## Replace images

- Open the page editor.
- Select the image block.
- Click Replace and upload a new image.

## Edit CTA and form details

- Update the call-to-action text directly in the website content or via the theme customizer.
- Adjust the header CTA in Appearance → Customize → Theme Options.

## Customization

The theme includes global design tokens inside `theme.json` for:
- primary dark
- secondary dark
- accent gold
- background
- white
- text
- muted text
- border

## Notes

This theme is designed to be easy for a non-technical client to manage without editing code. Most content is edited through the WordPress editor and media library.

## Recommended optional plugins

- Rank Math or Yoast SEO
- LiteSpeed Cache or WP Fastest Cache
- Smush or ShortPixel for image optimization

